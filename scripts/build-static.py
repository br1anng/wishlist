"""Build a deployable static site that also works under a GitHub Pages repo path."""
from pathlib import Path
import json
import shutil

root = Path(__file__).resolve().parents[1]
out = root / 'dist'
marker = out / '.wishlist-build'
if out.exists():
    if not marker.is_file():
        raise SystemExit('Refusing to overwrite an existing dist directory without a build marker')
    shutil.rmtree(out)
out.mkdir()
marker.write_text('Generated by scripts/build-static.py\n')
script = (root / 'app.js').read_text()
start = script.index('const gifts=') + len('const gifts=')
gifts, consumed = json.JSONDecoder().raw_decode(script[start:])
for wish in gifts:
    image = wish.get('image')
    if not image or not image.startswith('/assets/products/'):
        continue
    source = root / image.lstrip('/')
    if not source.is_file():
        raise SystemExit('Missing product image: ' + str(source))
    target = out / image.lstrip('/')
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    wish['image'] = '.' + image
script = script[:start] + json.dumps(gifts, ensure_ascii=False, indent=2) + script[start+consumed:]
(out / 'app.js').write_text(script)
html = (root / 'index.html').read_text()
html = html.replace('href="/style.css"', 'href="./style.css"')
html = html.replace('src="/app.js"', 'src="./app.js"')
html = html.replace('href="/"', 'href="./"')
(out / 'index.html').write_text(html)
shutil.copyfile(root / 'style.css', out / 'style.css')
(out / '.nojekyll').touch()
for name in ['PatrickHand-OFL.txt', 'LilitaOne-OFL.txt']:
    target = out / 'assets' / 'licenses' / name
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(root / 'assets' / name, target)
shutil.copyfile(root / 'assets/products/sources.json', out / 'assets/products/sources.json')
shutil.copyfile(root / 'assets/products/kindle-dash-LICENSE.txt', out / 'assets/licenses/kindle-dash-LICENSE.txt')
print(f'Static site built: {out} ({len(gifts)} wishes)')
